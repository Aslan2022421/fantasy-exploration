// 小的二元堆積：照 key 由小到大取出
export function heap() {
  const keys = [];
  const vals = [];
  return {
    get size() {
      return keys.length;
    },
    push(k, v) {
      let i = keys.length;
      keys.push(k);
      vals.push(v);
      while (i > 0) {
        const p = (i - 1) >> 1;
        if (keys[p] <= keys[i]) break;
        [keys[p], keys[i]] = [keys[i], keys[p]];
        [vals[p], vals[i]] = [vals[i], vals[p]];
        i = p;
      }
    },
    pop() {
      const top = vals[0];
      const lastK = keys.pop();
      const lastV = vals.pop();
      if (keys.length) {
        keys[0] = lastK;
        vals[0] = lastV;
        let i = 0;
        for (;;) {
          const l = i * 2 + 1;
          const r = l + 1;
          let m = i;
          if (l < keys.length && keys[l] < keys[m]) m = l;
          if (r < keys.length && keys[r] < keys[m]) m = r;
          if (m === i) break;
          [keys[m], keys[i]] = [keys[i], keys[m]];
          [vals[m], vals[i]] = [vals[i], vals[m]];
          i = m;
        }
      }
      return top;
    },
  };
}

